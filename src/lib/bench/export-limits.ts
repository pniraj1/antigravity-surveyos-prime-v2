// Bench results → the committed per-model limits table (src/lib/ai/page-limits.ts).
import type { ModelLimit } from '../ai/page-limits';
import { passes } from './score';
import type { CellResult } from './store';

/** At one pages-per-call: pass on r1, or ≥ 2 passing runs with at most one failure (borderline 3rd run). */
const profilePasses = (cs: CellResult[]): boolean => {
  const ok = cs.filter(c => passes(c.errors)).length;
  return cs.length > 0 && (ok === cs.length || (ok >= 2 && cs.length - ok <= 1));
};

/** Densest call of a cell: rows on pages k·p+1 … (k+1)·p. */
const densestCall = (c: CellResult): number => {
  const per = new Map<number, number>();
  for (const r of c.rows) { const k = Math.floor((r.page - 1) / c.pagesPerCall); per.set(k, (per.get(k) ?? 0) + 1); }
  return Math.max(0, ...per.values());
};

export function proposeLimits(cells: CellResult[], hardIds: string[]): ModelLimit[] {
  const done = cells.filter(c => c.status === 'done');
  const groups = new Map<string, CellResult[]>();
  for (const c of done) { const k = JSON.stringify([c.model, c.method]); groups.set(k, [...(groups.get(k) ?? []), c]); }
  const out: ModelLimit[] = [];
  for (const cs of groups.values()) {
    const steps = [...new Set(cs.map(c => c.pagesPerCall))].sort((a, b) => b - a);
    const p = steps.find(p => {
      const at = cs.filter(c => c.pagesPerCall === p);
      const hardOk = hardIds.every(id => profilePasses(at.filter(c => c.profileId === id && c.imageScale === 1.5)));
      return hardOk && at.filter(c => !hardIds.includes(c.profileId)).every(c => passes(c.errors));
    });
    if (p === undefined) continue;
    const at = cs.filter(c => c.pagesPerCall === p && passes(c.errors));
    const imageScale = ([1, 1.25, 1.5] as const).find(s => at.some(c => c.imageScale === s)
      && cs.filter(c => c.pagesPerCall === p && c.imageScale === s).every(c => passes(c.errors))) ?? 1.5;
    out.push({
      model: cs[0].model, method: cs[0].method, maxRowsPerCall: Math.min(...at.map(densestCall)), maxPagesPerCall: p, imageScale,
      measuredAt: new Date(Math.max(...cs.map(c => c.at))).toISOString().slice(0, 10), modelVersion: cs[0].modelVersion,
    });
  }
  return out;
}

const HEAD = `// Per-model page limits measured by the sandbox extraction bench.
// Generated by the bench's "Export limits table" button; commit only after owner approval.
// An empty table keeps today's chunking for every model.

export interface ModelLimit { model: string; method: 'text' | 'vision'; maxRowsPerCall: number; maxPagesPerCall: number; imageScale: 1 | 1.25 | 1.5; measuredAt: string; modelVersion: string }

export const PAGE_LIMITS: readonly ModelLimit[] = `;
const TAIL = `;

export function limitsFor(model: string, method: 'text' | 'vision', table: readonly ModelLimit[] = PAGE_LIMITS): ModelLimit | undefined {
  return table.find(l => l.model === model && l.method === method);
}
`;

/** Full page-limits.ts file text. */
export function limitsSource(limits: ModelLimit[]): string {
  return HEAD + JSON.stringify(limits, null, 2) + TAIL;
}
